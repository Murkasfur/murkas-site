/** Ссылка на ту же страницу на другом языке: /admin ↔ /ru/admin */
export function localizePath(path: string, lang: Lang) {
  const clean = path.replace(/^\/ru(?=\/|$)/, '') || '/';
  return lang === 'ru' ? (clean === '/' ? '/ru' : `/ru${clean}`) : clean;
}
